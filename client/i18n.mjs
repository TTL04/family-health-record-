const KEY = 'fhr.lang';
const LANGS = ['zh', 'en', 'both'];

export function currentLang() {
  const v = localStorage.getItem(KEY);
  return LANGS.includes(v) ? v : 'zh';
}

export function setLang(lang) {
  localStorage.setItem(KEY, LANGS.includes(lang) ? lang : 'zh');
  location.reload();
}

