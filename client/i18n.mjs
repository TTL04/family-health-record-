// 语言模式选择：中文 / English / 中英
export function t(cn, vars) {
  const en = DICT[cn];
  const lang = currentLang();
  let out = lang === 'en'
    ? (en || cn)
    : lang === 'both'
      ? (en && en !== cn ? `${cn} / ${en}` : cn)
      : cn;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

// 把静态节点渲染成当前语言。data-i18n-html 允许文案里带 <strong> 等标签。
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-html]')) {
    el.innerHTML = t(el.dataset.i18nHtml);
  }
  for (const el of root.querySelectorAll('[data-i18n-ph]')) {
    el.placeholder = t(el.dataset.i18nPh);
  }
  const pageTitle = document.documentElement.dataset.title;
  if (pageTitle) document.title = `${t(pageTitle)} · ${t('家庭健康档案')}`;
  document.documentElement.lang = currentLang() === 'en' ? 'en' : 'zh-CN';
}

// 语言切换条：优先放进页头第一行（.topline）的右侧，没有页头就放最上方。
// 登录页若预置了 #langSlot 容器，就渲染到那里。
export function mountLangSwitch() {
  if (document.getElementById('langBar')) return;
  let bar = document.getElementById('langSlot');
  if (bar) {
    bar.id = 'langBar';
    bar.className = 'lang-bar';
  } else {
    bar = document.createElement('div');
    bar.className = 'lang-bar';
    bar.id = 'langBar';
    const top = document.querySelector('.topline');
    if (top) {
      top.appendChild(bar);
    } else {
      const host = document.querySelector('header') || document.body;
      host.insertBefore(bar, host.firstChild);
    }
  }
  bar.innerHTML = `<div class="lang-switch" role="group" aria-label="Language">
    ${[['zh', '中文'], ['en', 'English'], ['both', '中英']].map(([v, label]) =>
      `<button type="button" data-lang="${v}"${currentLang() === v ? ' class="active"' : ''}>${label}</button>`).join('')}
  </div>`;
  bar.addEventListener('click', event => {
    const btn = event.target.closest('[data-lang]');
    if (btn) setLang(btn.dataset.lang);
  });
}

// 页面初始化：一次调用搞定挂载 + 渲染。
export function initI18n() {
  mountLangSwitch();
  applyI18n();
}
